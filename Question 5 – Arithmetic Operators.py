# Problem

# Take two numbers as input from the user.

# Print:

# Addition
# Subtraction
# Multiplication
# Division
# Example

# Input

# 10
# 5

# Output

# Addition: 15
# Subtraction: 5
# Multiplication: 50
# Division: 2.0

num1 = int(input("Enter your num 1 : "));
num2 = int(input("Enter your num 2 : "));

add = num1 + num2;
sub = num1 - num2;
multi = num1*num2;
div = num1/num2;

print("Addition:",add);
print("Subtraction:",sub);
print("Multiplication:",multi);
print("Division:",div);


